# EXTENSION BRIDGE
# ──────────────────────────────────────────────────────────────

_extension_inbox: Dict[str, Dict] = {}
_extension_results: Dict[str, Dict] = {}
_extension_lock = threading.Lock()
_extension_last_seen = {"t": 0.0}

@app.get("/api/extension/inbox")
async def extension_inbox():
    _extension_last_seen["t"] = time.time()
    with _extension_lock:
        if _extension_inbox:
            cmd_id = next(iter(_extension_inbox))
            return JSONResponse(_extension_inbox.pop(cmd_id))
    return JSONResponse({})

@app.post("/api/extension/result")
async def extension_result(payload: dict):
    cmd_id = payload.get("id")
    if not cmd_id:
        raise HTTPException(status_code=400, detail="Missing id")
    with _extension_lock:
        _extension_results[cmd_id] = payload.get("result")
    return JSONResponse({"ok": True})

@app.get("/api/extension/status")
async def extension_status():
    delta = time.time() - _extension_last_seen["t"]
    return JSONResponse({"alive": delta < 15, "last_seen_seconds": round(delta, 1)})

@app.post("/api/vk-command")
async def vk_command(playlist_url: str = Form(...)):
    if not playlist_url.strip():
        raise HTTPException(status_code=400, detail="Missing playlist URL")
    cmd_id = str(uuid.uuid4())
    with _extension_lock:
        _extension_inbox[cmd_id] = {
            "id": cmd_id,
            "action": "extractPlaylist",
            "playlistUrl": playlist_url.strip(),
        }
    return JSONResponse({"command_id": cmd_id})

@app.get("/api/vk-command/{command_id}")
async def vk_command_status(command_id: str):
    with _extension_lock:
        if command_id in _extension_results:
            return JSONResponse({"status": "done", "result": _extension_results.pop(command_id)})
    return JSONResponse({"status": "pending"})


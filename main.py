def load_config() -> Dict:
    if CONFIG_PATH.exists():
        try:
            return json.loads(CONFIG_PATH.read_text(encoding="utf-8"))
        except Exception:
            pass
    return {}

def save_config(cfg: Dict) -> None:
    CONFIG_PATH.write_text(json.dumps(cfg, indent=2, ensure_ascii=False), encoding="utf-8")

def write_sockseek_conf(username: str, password: str, output_dir: str) -> None:
    content = f"""# Generated by setup - do not edit manually
username = {username}
password = {password}
pref-format = flac,mp3
pref-min-bitrate = 320
pref-strict-title = true
pref-strict-artist = true
pref-strict-album = true
pref-length-tol = 5
output-dir = {output_dir}
"""
    SOULSEEK_CONF_PATH.write_text(content, encoding="utf-8")

def is_configured() -> bool:
    cfg = load_config()
    return bool(cfg.get("configured")) and SOULSEEK_CONF_PATH.exists()


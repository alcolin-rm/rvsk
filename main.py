@app.post("/api/download")
async def download(
    background_tasks: BackgroundTasks,
    track_list: str = Form(...),
    album_mode: bool = Form(False),
    playlist_name: str = Form(""),
    format_pref: str = Form("flac,mp3"),
    min_bitrate: int = Form(192),
    pref_bitrate: int = Form(320),
    length_tol: int = Form(5),
):
    tracks = parse_track_list(track_list)
    if not tracks:
        raise HTTPException(status_code=400, detail="No tracks parsed from list")

    cfg = load_config()
    output_root = cfg.get("output_dir", str(BASE_DIR / "downloads"))
    folder_name = derive_folder_name(tracks, playlist_name)
    output_dir = str(Path(output_root) / folder_name)

    job_id = hashlib.md5(f"{datetime.now().isoformat()}".encode()).hexdigest()[:12]
    jobs[job_id] = {
        "id": job_id,
        "status": "starting",
        "total": len(tracks),
        "downloaded": 0,
        "failed": 0,
        "skipped": 0,
        "progress": 0.0,
        "message": f"Queued {len(tracks)} tracks",
        "created": datetime.now().isoformat(),
        "album_mode": album_mode,
        "folder_name": folder_name,
        "output_dir": output_dir,
        "log": [],
        "tracks": tracks,
        "leechers": {},
        "counted_tracks": [],
        "browse_entries": [],
        "browse_index": {},
        "workflow_id": None,
    }

    def progress_cb(current: int, total: int, message: str = ""):
        jobs[job_id]["downloaded"] = current
        jobs[job_id]["progress"] = current / max(total, 1)
        jobs[job_id]["message"] = message or f"({current}/{total}) downloading"

    def log_cb(line: str):
        job = jobs[job_id]
        job["log"].append(line)
        if len(job["log"]) > 500:
            job["log"] = job["log"][-500:]

    async def run():
        try:
            jobs[job_id]["status"] = "searching"
            jobs[job_id]["message"] = "Waiting for Sockseek daemon..."
            
            # Wait for the daemon to be fully connected to Soulseek (up to 30s)
            for _ in range(30):
                if await daemon_is_ready():
                    break
                await asyncio.sleep(1)
                
            if not await daemon_is_alive():
                jobs[job_id]["status"] = "error"
                jobs[job_id]["message"] = "Sockseek daemon not reachable."
                return

            # Canonicalize manual input via iTunes Search API
            from metadata_fixer import canonicalize_tracks
            
            final_tracks = tracks
            if len(tracks) <= 20 and all(not t.get("album") for t in tracks):
                jobs[job_id]["message"] = "Correcting track metadata..."
                final_tracks = await canonicalize_tracks(tracks)

                for orig, new in zip(tracks, final_tracks):
                    if orig.get("artist") != new.get("artist") or orig.get("title") != new.get("title"):
                        msg = f"Fixed: '{orig.get('artist')} - {orig.get('title')}' -> '{new.get('artist')} - {new.get('title')}'"
                        log_cb(msg)
                        jobs[job_id]["message"] = f"Corrected: {new.get('artist')} - {new.get('title')}"

            jobs[job_id]["message"] = "Submitting to Sockseek daemon..."
            
            summary = await submit_extract_job(
                tracks=final_tracks,
                job_id=job_id,
                output_dir=output_dir,
                format_pref=format_pref,
                min_bitrate=min_bitrate,
                pref_bitrate=pref_bitrate,
                length_tol=length_tol,
                album_mode=album_mode,
                playlist_name=playlist_name,
            )

            workflow_id = summary.get("workflowId")
            root_job_id = summary.get("jobId")
            
            if not workflow_id:
                jobs[job_id]["status"] = "error"
                jobs[job_id]["message"] = "Daemon did not return a workflow id"
                return

            jobs[job_id]["workflow_id"] = workflow_id
            jobs[job_id]["status"] = "running"
            jobs[job_id]["message"] = "Daemon accepted the job"

            await mirror_workflow(
                jobs[job_id],
                workflow_id,
                root_job_id=root_job_id,
                log_cb=log_cb,
                progress_cb=progress_cb,
            )

        except Exception as e:
            import traceback
            tb = traceback.format_exc()
            jobs[job_id]["status"] = "error"
            jobs[job_id]["message"] = str(e)
            jobs[job_id]["log"].append(f"ERROR: {e}")
            jobs[job_id]["log"].append(tb)
            print(f"[Job {job_id}] ERROR: {e}\n{tb}")

    background_tasks.add_task(run)
    return JSONResponse({"job_id": job_id, "total": len(tracks), "folder_name": folder_name})


def _kill_all_sockseek():
    if sys.platform == "win32":
        subprocess.run(["taskkill", "/F", "/IM", "sockseek.exe"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    else:
        subprocess.run(["pkill", "-9", "-f", "sockseek"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)

def _spawn_daemon():
    global _daemon_pid
    if not SOCKSEEK_BIN.exists():
        print(f"[daemon] sockseek.exe not found at {SOCKSEEK_BIN}")
        return None

    _kill_all_sockseek()
    time.sleep(0.5)

    log_path = BASE_DIR / "daemon.log"
    creation_flags = 0
    if sys.platform == "win32":
        creation_flags = subprocess.CREATE_NEW_PROCESS_GROUP | 0x00000008

    try:
        proc = subprocess.Popen(
            [str(SOCKSEEK_BIN), "daemon", "--server-port", str(DAEMON_PORT), "--log-file", str(log_path)],
            cwd=str(BASE_DIR), stdout=None, stderr=None, stdin=subprocess.DEVNULL, creationflags=creation_flags,
        )
        _daemon_pid = proc.pid
        print(f"[daemon] Spawned sockseek daemon, pid={proc.pid}")
        return proc.pid
    except Exception as e:
        print(f"[daemon] Failed to spawn: {e}")
        return None

def _kill_daemon():
    global _daemon_pid
    if _daemon_pid is None: return
    try:
        if sys.platform == "win32":
            subprocess.run(["taskkill", "/F", "/T", "/PID", str(_daemon_pid)], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        else:
            os.kill(_daemon_pid, signal.SIGTERM)
        print(f"[daemon] Killed pid={_daemon_pid}")
    except Exception as e:
        print(f"[daemon] Kill failed: {e}")
    _daemon_pid = None

atexit.register(_kill_daemon)

@app.on_event("startup")
async def startup_event():
    pid = _spawn_daemon()
    if pid:
        for _ in range(20):
            await asyncio.sleep(0.5)
            if await daemon_is_alive():
                print(f"[daemon] Daemon is up at {DAEMON_URL}")
                return
        print("[daemon] Daemon did not come up within 10 seconds")

@app.on_event("shutdown")
async def shutdown_event():
    _kill_daemon()

